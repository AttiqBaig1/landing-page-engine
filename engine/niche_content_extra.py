"""
niche_content_extra.py
----------------------
60 additional niches for the landing page engine, in the same schema as
niche_content.py (merged into NICHE_CONTENT there).

Written with the compact N(...) helper below:
  * service slugs are generated from the service name,
  * each service names its own Lucide icon ("lucide:...") so cards get a
    meaningful icon even when no keyword in generate_site.ICON_MAP matches,
  * "&" is HTML-escaped automatically (the templates expect &amp;).

Extra optional keys understood by the engine:
  photos   -> borrow another niche's photo_library folder when this niche
              has none of its own (drop real photos into
              photo_library/<niche>/original/ to override)
  radius   -> (miles, min_population) for the nearby service-area search
  audience -> who the reviews speak for ("Homeowners" by default)
"""
import re

EXTRA_NICHES = {}


def _esc(s: str) -> str:
    return re.sub(r"&(?!amp;|quot;|#39;|lt;|gt;)", "&amp;", s)


def _slug(s: str) -> str:
    s = s.lower().replace("&", "and")
    return re.sub(r"[^a-z0-9]+", "-", s).strip("-")


def N(key, theme, logo, tagline, kw, hook, sub, badges, services, faq, stats,
      about_h2, about_body, cta, photos=None, radius=None, audience=None):
    assert len(badges) == 4 and len(services) == 6 and len(faq) == 4 and len(stats) == 4, key
    d = {
        "theme": theme,
        "logo": "lucide:" + logo,
        "tagline": _esc(tagline),
        "h1_keyword": _esc(kw),
        "hero_hook": _esc(hook),
        "hero_sub": _esc(sub),
        "badges": [_esc(b) for b in badges],
        "services": [(_slug(n), _esc(n), "lucide:" + ic, _esc(desc)) for n, ic, desc in services],
        "faq": [(_esc(q), _esc(a)) for q, a in faq],
        "stats": stats,
        "about_h2": _esc(about_h2),
        "about_body": [_esc(p) for p in about_body],
        "cta_h2": _esc(cta),
    }
    if photos:
        d["photos"] = photos
    if radius:
        d["radius"] = radius
    if audience:
        d["audience"] = audience
    EXTRA_NICHES[key] = d


